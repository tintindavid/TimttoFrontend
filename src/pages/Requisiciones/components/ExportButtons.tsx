import React from 'react';
import { Button, Spinner } from 'react-bootstrap';
import { FaFileExcel, FaFilePdf } from 'react-icons/fa';
import { toast } from 'react-toastify';
import { useExportarComparativo, useExportarRequisicion } from '@/hooks/useRequisicionReportes';
import type { ExportFormato } from '@/services/requisicionReportes.service';
import { getRequisicionErrorMessage } from '@/utils/requisicionErrors';
import ReqHelp from '../help/ReqHelp';

interface Props {
  requisicionId: string;
  consecutivo?: string;
  /** `requisicion`: whole-document PDF / Excel; `comparativo`: quotations comparison. */
  kind: 'requisicion' | 'comparativo';
  size?: 'sm';
}

/** "Descargar PDF" / "Descargar Excel" buttons; the file is generated by the server when asked. */
const ExportButtons: React.FC<Props> = ({ requisicionId, consecutivo, kind, size }) => {
  const requisicionExport = useExportarRequisicion();
  const comparativoExport = useExportarComparativo();
  const mutation = kind === 'comparativo' ? comparativoExport : requisicionExport;
  const what = kind === 'comparativo' ? 'el comparativo' : 'la requisición';
  const de = kind === 'comparativo' ? 'del comparativo' : 'de la requisición';

  const run = async (formato: ExportFormato) => {
    try {
      await mutation.mutateAsync({ id: requisicionId, formato, consecutivo });
    } catch (err) {
      toast.error(
        getRequisicionErrorMessage(err, `No fue posible descargar ${what} en ${formato === 'pdf' ? 'PDF' : 'Excel'}.`)
      );
    }
  };

  const busyFormato = mutation.isLoading ? mutation.variables?.formato : undefined;

  return (
    <span className="d-inline-flex align-items-center gap-2" data-testid={`export-${kind}`}>
      <Button
        size={size}
        variant="outline-secondary"
        disabled={mutation.isLoading}
        aria-label={`Descargar PDF ${de}`}
        onClick={() => run('pdf')}
      >
        {busyFormato === 'pdf' ? <Spinner as="span" size="sm" animation="border" className="me-2" /> : <FaFilePdf className="me-2" aria-hidden="true" />}
        Descargar PDF
      </Button>
      <Button
        size={size}
        variant="outline-success"
        disabled={mutation.isLoading}
        aria-label={`Descargar Excel ${de}`}
        onClick={() => run('xlsx')}
      >
        {busyFormato === 'xlsx' ? <Spinner as="span" size="sm" animation="border" className="me-2" /> : <FaFileExcel className="me-2" aria-hidden="true" />}
        Descargar Excel
      </Button>
      <ReqHelp id={kind === 'comparativo' ? 'accion.exportarComparativo' : 'accion.exportarDetalle'} className="ms-0" />
    </span>
  );
};

export default ExportButtons;
